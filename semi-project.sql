    SELECT table_name
      FROM user_tables
     WHERE table_name IN (
       'ASSIGNMENT_SUBMISSION', 'REPLY', 'CHAPTER_PROGRESS', 'NOTICE', 'QNA',
       'LEAVE_REQUEST', 'ASSIGNMENT', 'CHAPTER', 'ENROLLMENT', 'COURSE_TARGET',
       'COURSE', 'ATTACHMENT', 'MEMBER', 'DEPARTMENT', 'POSITION'
     )
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
